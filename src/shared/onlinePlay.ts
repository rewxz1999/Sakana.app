/**
 * 在线播放链路的时间口径（v0.3.9 统一）。
 *
 * 为什么要单独一个文件：这条链路上的超时过去散落在六七个模块里
 * （`ruleProbe` 的播放页直出 8s / 直链校验 12s / HEAD 预筛 6s、`ruleWebview` 的
 * 30s 兜底、渲染层的 15s 直连看门狗 / 12s 重嗅探兜底 / 20s attach / 45s 嗅探看门狗、
 * FFmpeg 中转的 30s 判定），每一个都是各自拍出来的数字 ——
 * 结果就是「同一个站点的失败判定时间取决于走的是哪条分支」，用户看到的是
 * 「有时候 15 秒就报失败，有时候等 45 秒」，非常难以理解。
 *
 * 现在统一成 **60 秒**，理由：
 *   · 实测慢 CDN + 冷启动 + 24 分钟长片的 HLS 主列表+m3u8 分片首字节经常要 20–40 秒
 *     （`.e2e/online-test-v037.log` 里 7sefun/AGE 这类站点都出现过 20s 以上才出首帧）；
 *   · 用户明确要求「只要能获取到一点资源就不该结束」——
 *     60 秒是**首字节**的等待上限，不是「必须播起来」的上限；
 *   · 一旦开始有数据在动，就改用 `ONLINE_IDLE_TIMEOUT_MS` 的**空闲**口径
 *     （见 streamDiag：连续 60 秒一个字节都没有才算断），所以「慢」永远不会被判成「失败」。
 */
export const ONLINE_PLAY_TIMEOUT_MS = 60_000

/**
 * 「还在动就不算超时」：数据已经流动起来之后，允许的**无数据**间隔。
 *
 * 与上面的区别很重要：上面管「等第一个字节」，这里管「流着流着停了」。
 * HLS 直播/长片在换分片、CDN 回源、播放器 seek 时出现十几秒没有新字节是正常的，
 * 所以这里也取 60 秒 —— 只有「连续一分钟一个字节都没到」才判定连接已断。
 */
export const ONLINE_IDLE_TIMEOUT_MS = 60_000

/**
 * 「资源获取速度过慢」的判据（字节/秒）。
 *
 * 取值依据：本项目的目标画质是 1080p（HLS 主列表里 AVERAGE-BANDWIDTH 普遍 2–6 Mbps），
 * 200 KB/s ≈ 1.6 Mbps —— 低于这个速率已经**不可能**跟得上 1080p 的实时码率，
 * 用户看到的就是「一直在缓冲、每隔几秒卡一下」，必须如实告诉他而不是装作正常。
 *
 * ⚠️ 判定为「过慢」**不等于失败**：按用户要求，这时继续等、继续显示实时速率，
 * 只有「一个字节都拿不到」才判失败（见 streamDiag.verdictOf）。
 */
export const SLOW_STREAM_RATE_BPS = 200 * 1024

/**
 * 速率判定的采样窗口：至少攒够这么久的数据才下结论。
 *
 * 为什么不能一拿到首字节就算速率：首字节之后的几百毫秒里速率是爆表的
 * （TCP 窗口 + 服务器预推），拿那一瞬间的数字判「快」会把慢站点误判成正常。
 */
export const SPEED_SAMPLE_WINDOW_MS = 4_000

/**
 * 连续多久低于 SLOW_STREAM_RATE_BPS 才提示「过慢」。
 *
 * 给 8 秒是为了躲开 HLS 换分片的正常停顿（一个 6 秒分片下完到下一个分片开始之间，
 * 瞬时速率必然掉到 0）—— 那不属于「站点慢」，报出来只会制造噪音。
 */
export const SLOW_STREAM_CONFIRM_MS = 8_000

/**
 * FFmpeg 中转「准备就绪」的等待上限，与整条链路口径一致（60 秒）。
 *
 * 中转要等 FFmpeg 连上源站、缓冲一段、再吐出第一个 MP4 分片，
 * 长片冷启动超过 12 秒是常态（旧代码就是按 12/30 秒两档判定的）。
 */
export const RELAY_READY_TIMEOUT_MS = ONLINE_PLAY_TIMEOUT_MS

/**
 * attach（内核挂载）的等待上限。
 *
 * 为什么也归到这一档：libmpv 初始化 + 创建原生子窗口在低端机上偶发慢，
 * 而旧代码是 20 秒就投降并显示「播放内核初始化超时」——
 * 结果在慢机器上「第一次进播放页必失败、第二次就好」，用户只会觉得播放器时好时坏。
 */
export const ENGINE_ATTACH_TIMEOUT_MS = ONLINE_PLAY_TIMEOUT_MS
