import type { StreamBoostMode, StreamBoostStatus } from './types'

/**
 * 在线播放加速（v0.3.9 优化器）的共享口径。
 *
 * 这个文件的唯一职责是让「主进程怎么算」与「界面上怎么写」用的是同一组数字，
 * 避免出现「设置页说阈值 1MB/s、代码里其实是 3MB/s」这种对不上的情况。
 *
 * ## 先有实测，再有这些常量
 *
 * `.e2e/measure-boost.mjs` 在真实源上量过（2026-10-11，本机）：
 *
 *   MXdm（svip.yyzy-play.vip，HLS 370 片/1479s）前 8 个分片：
 *     顺序取（=播放器的行为）359KB/s → 3.87 视频秒/秒
 *     4 路并发预读              769KB/s → 8.28 视频秒/秒（+114%）
 *   baimao（v.lzv22.com，HLS 368 片/1470s）前 8 个分片：
 *     顺序 279KB/s → 2.29 视频秒/秒；4 路并发 657KB/s → 5.38 视频秒/秒（+135%）
 *
 * 结论：这类 MacCMS CDN **按连接限速**，单连接拿到的那点带宽还不够 1080p 实时播放，
 * 而播放器（libmpv）取 HLS 是**一个分片一个请求、串行**的 —— 所以并发预读就是这阶段真正的优化点。
 */

/**
 * 「直连已经够快，不必加一层中转」的阈值（字节/秒）。
 *
 * 1.5MB/s ≈ 12Mbps：1080p 的 AVERAGE-BANDWIDTH 普遍 2–6Mbps，
 * 12Mbps 已经留了 2 倍以上余量去扛抖动/换分片。低于它的源才值得并发加速；
 * 高于它再加一层只会白白多一次本机转发（用户要的也是「先直连、测到慢再加速」）。
 */
export const BOOST_FAST_BPS = 1.5 * 1024 * 1024

/**
 * HLS 的第二个「够快」判据：**单连接取片速度相对该片时长的余量**。
 *
 * 判据形式：`该分片时长 / 取回耗时 ≥ 10` 才算「单连接本来就够用」。
 *
 * 为什么要它（两条实测教训）：
 *  1. 每连接 3MB/s 的源上，一片 300KB 只要 200ms，但一次 HTTP 往返 + undici/libcurl 调度
 *     本身就有 100~200ms，于是「按字节算速率」在小分片上有个测不准的地板（只能量出 ~1.4MB/s）
 *     —— 只看速率会把这种**明显很快**的源误判成慢；
 *  2. 反过来，全站限速 1MB/s 的源上一片 300KB 也只要 300ms（该片时长的 1/20），
 *     播放其实永远追得上 —— 加一层中转只会白折腾。
 * 余量 ≥10 倍意味着「下载 6 秒的片只要 0.6 秒内」，留足了抖动空间；
 * 而 MXdm/baimao 实测单连接一片要 0.7~1.3 秒（余量 4~8 倍）→ 判为「值得加速」。
 */
export const BOOST_FAST_SEGMENT_MARGIN = 10

/** 测速预算：最多花这么久去判断快慢（超时就按「慢」处理，因为慢的源本来就会超时） */
export const BOOST_MEASURE_MAX_MS = 3_000

/** 起播预热预算：把地址交给播放器之前最多先拉这么久的数据，超时就带着已有数据起播 */
export const BOOST_WARM_MAX_MS = 2_500

/** 文件型直链的分片下载块大小（并发 Range 的粒度） */
export const BOOST_CHUNK_BYTES = 2 * 1024 * 1024

/** 并发连接数：文件型 = 并发 Range；HLS = 并发预读分片数（实测 4 路收益最大） */
export const BOOST_PARALLEL = 4

/**
 * 优化记录的条数上限（v0.3.9 补充更新）。
 *
 * 为什么是 **10**（用户要求「优化记录只保存 10 条」）：
 * 这个列表要回答的是「最近几次加速到底有没有用」，不是拿来做长期统计 ——
 * 界面上默认也只展示最近 1 条、其余折叠，留 100 条既没人翻、又让每次落盘都拖着几十 KB 历史。
 * 10 条 × 约 430 字节 ≈ 4.3KB（实测单条体积）。
 *
 * 旧版本可能已经存了上百条：不需要迁移脚本 —— 下一次写入时按这个上限裁掉多余的（见 flushRecord）。
 */
export const BOOST_RECORD_MAX = 10

/**
 * 一条会话至少要转发这么多字节才值得记进优化记录。
 *
 * 为什么不是「一开会话就记」：用户点进去又马上退出、或者源站立刻失效时会话只走了几 KB，
 * 那种记录既没有速率样本也没有参考价值，只会把记录列表冲成一堆噪音（而且会挤掉真正有效的记录）。
 */
export const BOOST_RECORD_MIN_BYTES = 512 * 1024

/**
 * 记录落盘的最小间隔（毫秒）。
 *
 * 为什么不是每秒钟都写：日志式记录会在长片播放过程中反复写同一个文件；
 * 5 秒一次既能保证「播放中途崩溃也留下了记录」，又把写盘次数压到很低
 * （store 本身还有 250ms 防抖 + tmp+rename 原子替换）。
 */
export const BOOST_RECORD_FLUSH_MS = 5_000

/**
 * VOD 播放列表在本机中转里的缓存时长（毫秒）。
 *
 * 起因是一条自检里量到的真实数字（2026-10-11）：`localTtfbMs`（播放器从本机拿首字节）
 * 竟然是 1.2~1.8 秒 —— 排查发现是「播放器请求播放列表 → 我们再向 CDN 拉一遍」，
 * 慢站点上这一趟往返就是一两秒，等于把预热省下的时间又还回去了（实测记录里记得一清二楚）。
 *
 * 所以：**VOD（列表里有 #EXT-X-ENDLIST）**的播放列表在中转会话里缓存 30 秒，
 * 播放器这次请求直接命中内存；**直播列表不缓存**（它会滚动变化，缓存住就是让播放器看旧片段）。
 */
export const BOOST_PLAYLIST_TTL_MS = 30_000

/**
 * 会话缓冲上限（字节）。
 *
 * 为什么 24MB：并发窗口本身就是内存的天然上限（4 × 2MB = 8MB，加在途/待写的最多 12MB），
 * 这个上限是**第二道闸**：客户端卡住不读时，超过它就不再开新的分片请求。
 * 实测 HLS 1080p 一个分片约 300–500KB，24MB 已经够存 1 分钟以上的视频 ——
 * 再深就没有意义了（长缓冲是播放器自己 cache 的职责，不是代理的）。
 */
export const BOOST_BUFFER_CAP_BYTES = 24 * 1024 * 1024

/** 会话空闲回收：这么久没有任何请求就拆掉（换集/退出播放器后不留后台连接） */
export const BOOST_SESSION_IDLE_MS = 90_000

/** 状态里 origin/local 这类地址只显示前多少个字符（界面上一行放得下） */
export const BOOST_URL_DISPLAY_CHARS = 120

/** 档位的人话说明（设置页与日志共用，避免两处措辞不一致） */
export const BOOST_MODE_LABEL: Record<StreamBoostMode, string> = {
  auto: '自动（先直连，测到慢再加速）',
  off: '关闭（完全直连）',
  force: '强制加速（跳过测速，直接走并发中转）'
}

/** 状态口径：这些类型在主进程组装，渲染层只读不改 */
export type { StreamBoostMode, StreamBoostStatus }
